def validate_max_repair_rounds(value: int) -> int:
    if type(value) is not int or not 0 <= value <= MAX_REPAIR_ROUNDS:
        raise ValueError(f"max_repair_rounds must be an integer from 0 to {MAX_REPAIR_ROUNDS}")
